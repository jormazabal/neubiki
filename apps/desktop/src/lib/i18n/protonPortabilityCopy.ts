/** Translates only owned UI copy; document names, paths and provider details remain untouched. */
export function usePortabilityCopy() {
  const locale = useUiLocale();
  const t = (text: string, values?: Record<string, string | number>) => {
    const value = locale === "en" ? english[text] ?? text : text;
    return values ? value.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
      Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : placeholder) : value;
  };
  return { locale, t };
}
